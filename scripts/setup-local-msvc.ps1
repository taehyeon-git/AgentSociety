<#
Creates an ignored, workspace-local MSVC link environment when Visual Studio's
link.exe is unavailable. Uses Rust's rust-lld and an existing Windows SDK.
No system installation or registry changes are performed.
#>
param([string]$WindowsSdkRoot = 'C:\Program Files (x86)\Windows Kits\10', [switch]$SkipVendor)
$ErrorActionPreference = 'Stop'
if ($env:OS -ne 'Windows_NT') { throw 'This optional setup script is for Windows only.' }
$projectRoot = Split-Path -Parent $PSScriptRoot
$cacheDir = Join-Path $projectRoot '.build-cache'
$archive = Join-Path $cacheDir 'msvc-store.vsix'
$expanded = Join-Path $cacheDir 'msvc-store'
$expectedHash = '9135b03c0df53c7a0aa9bef7230a1c2ff4263a0ee7baa7e419d034f484f6bb56'
$url = 'https://download.visualstudio.microsoft.com/download/pr/67cf767c-5e71-47c2-a54a-cd5631e28942/9135b03c0df53c7a0aa9bef7230a1c2ff4263a0ee7baa7e419d034f484f6bb56/Microsoft.VC.14.44.17.14.CRT.x64.Store.base.vsix'
$rustRoot = & rustc --print sysroot
if ($LASTEXITCODE -ne 0) { throw 'Install a stable Windows MSVC Rust toolchain first.' }
$lld = Join-Path $rustRoot 'lib\rustlib\x86_64-pc-windows-msvc\bin\rust-lld.exe'
if (-not (Test-Path -LiteralPath $lld)) { throw "Rust linker unavailable: $lld" }
$sdk = Get-ChildItem -LiteralPath (Join-Path $WindowsSdkRoot 'Lib') -Directory |
    Where-Object { (Test-Path -LiteralPath (Join-Path $_.FullName 'um\x64\kernel32.lib')) -and (Test-Path -LiteralPath (Join-Path $_.FullName 'ucrt\x64\ucrt.lib')) } |
    Sort-Object { [version]$_.Name } -Descending | Select-Object -First 1
if (-not $sdk) { throw 'Install a Windows SDK with x64 UM and UCRT libraries first.' }
$configPath = Join-Path $projectRoot '.cargo\config.toml'
if (Test-Path -LiteralPath $configPath) {
    $existing = Get-Content -LiteralPath $configPath -Raw
    if ($existing -notmatch 'Generated by scripts/setup-local-msvc.ps1|Local build environment, generated for this workstation') {
        throw "An existing user Cargo config will not be overwritten: $configPath"
    }
}
New-Item -ItemType Directory -Path $cacheDir -Force | Out-Null
if (-not (Test-Path -LiteralPath $archive)) {
    & curl.exe --fail --location --silent --show-error --max-time 120 --output $archive $url
    if ($LASTEXITCODE -ne 0) { throw 'Could not download the official Microsoft CRT package.' }
}
if ((Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $expectedHash) {
    throw 'CRT package SHA-256 does not match the official release manifest.'
}
if (-not (Test-Path -LiteralPath $expanded)) {
    Add-Type -AssemblyName System.IO.Compression.FileSystem
    [System.IO.Compression.ZipFile]::ExtractToDirectory($archive, $expanded)
}
$crt = Join-Path $expanded 'Contents\VC\Tools\MSVC\14.44.35207\lib\x64'
if (-not (Test-Path -LiteralPath (Join-Path $crt 'msvcrt.lib'))) { throw 'Extracted CRT libraries are incomplete.' }
$nativeLibraries = "$crt;$(Join-Path $sdk.FullName 'um\x64');$(Join-Path $sdk.FullName 'ucrt\x64')"
$config = "# Generated by scripts/setup-local-msvc.ps1; local paths, do not commit.`n[target.x86_64-pc-windows-msvc]`nlinker = '$lld'`n`n[env]`nLIB = { value = '$nativeLibraries', force = false }`n"
# TLS crypto and SQLite's bundled C source need a compiler as well as the Rust linker.
# Official signed Microsoft payloads are extracted only inside this workspace.
$compilerPackages = @(
    @{
        Name = 'msvc-tools'; Hash = 'f4ad3cee4ef18e9f36382399261de27be6910ab3467178d7e687377ec841306d'
        Url = 'https://download.visualstudio.microsoft.com/download/pr/aa209763-134c-427b-9960-9ca54ccc1734/f4ad3cee4ef18e9f36382399261de27be6910ab3467178d7e687377ec841306d/Microsoft.VC.14.44.17.14.Tools.HostX64.TargetX64.base.vsix'
    },
    @{
        Name = 'msvc-headers'; Hash = '852382a9aa73502b7849c1bcadfb603ba7175c4e8b60e6aba03c7de711d4ece5'
        Url = 'https://download.visualstudio.microsoft.com/download/pr/c610cd8c-801b-44b8-a80a-82cc382aeb43/852382a9aa73502b7849c1bcadfb603ba7175c4e8b60e6aba03c7de711d4ece5/Microsoft.VC.14.44.17.14.CRT.Headers.base.vsix'
    },
    @{
        Name = 'msvc-res'; Hash = '603375e4d6d639bc6e0a7d0d657b17e0c3b72e52450f78eb41e987f40c3b5305'
        Url = 'https://download.visualstudio.microsoft.com/download/pr/aa209763-134c-427b-9960-9ca54ccc1734/603375e4d6d639bc6e0a7d0d657b17e0c3b72e52450f78eb41e987f40c3b5305/Microsoft.VC.14.44.17.14.Tools.HostX64.TargetX64.Res.base.enu.vsix'
    }
)
foreach ($package in $compilerPackages) {
    $packageArchive = Join-Path $cacheDir ($package.Name + '.vsix')
    if (-not (Test-Path -LiteralPath $packageArchive)) {
        & curl.exe --fail --location --silent --show-error --max-time 120 --output $packageArchive $package.Url
        if ($LASTEXITCODE -ne 0) { throw ('Could not download ' + $package.Name) }
    }
    if ((Get-FileHash -LiteralPath $packageArchive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $package.Hash) { throw 'Compiler package SHA-256 mismatch.' }
    $destination = Join-Path $cacheDir $package.Name
    if (-not (Test-Path -LiteralPath $destination)) {
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        [System.IO.Compression.ZipFile]::ExtractToDirectory($packageArchive, $destination)
    }
}
$compilerDir = Join-Path $cacheDir 'msvc-tools\Contents\VC\Tools\MSVC\14.44.35207\bin\Hostx64\x64'
$compilerResources = Join-Path $cacheDir 'msvc-res\Contents\VC\Tools\MSVC\14.44.35207\bin\Hostx64\x64\1033'
# cl.exe requires its language resource even for preprocessing and compiler detection.
Copy-Item -LiteralPath $compilerResources -Destination $compilerDir -Recurse -Force
$headerDir = Join-Path $cacheDir 'msvc-headers\Contents\VC\Tools\MSVC\14.44.35207\include'
$sdkInclude = Join-Path $WindowsSdkRoot ('Include\' + $sdk.Name)
$includePaths = "$headerDir;$(Join-Path $sdkInclude 'ucrt');$(Join-Path $sdkInclude 'shared');$(Join-Path $sdkInclude 'um')"
$config += "CC_x86_64_pc_windows_msvc = { value = '$(Join-Path $compilerDir 'cl.exe')', force = false }`nAR_x86_64_pc_windows_msvc = { value = '$(Join-Path $compilerDir 'lib.exe')', force = false }`nINCLUDE = { value = '$includePaths', force = false }`n"
if (-not $SkipVendor -and (Test-Path -LiteralPath (Join-Path $cacheDir 'vendor'))) {
    $config += "`n[source.crates-io]`nreplace-with = 'workspace-vendor'`n`n[source.workspace-vendor]`ndirectory = '.build-cache/vendor'`n"
}
New-Item -ItemType Directory -Path (Split-Path -Parent $configPath) -Force | Out-Null
[System.IO.File]::WriteAllText($configPath, $config)
Write-Output "Workspace linker ready. Windows SDK: $($sdk.Name). Run cargo build --workspace."
